// source-removal.test.mjs — Bjakcareer and We Work Remotely are REMOVED sources, and this is what
// stops them coming back.
//
// WHY THEY WENT:
//
//   Bjakcareer — high volume and low signal: the same titles repeated across many countries. Every
//   slot it takes is a slot a real match does not get, and a person only gets one role at a time.
//
//   We Work Remotely — its feed carried postings that were not on the employer's own careers site,
//   tagged "Anywhere in the World" while the body contradicted the tag. A source that cannot be
//   trusted on WHO is hiring, or WHERE, is worse than no source.
//
// WHY A TEST AND NOT A COMMENT: the watchlist is thousands of entries long and regenerated by
// tooling, so a re-add is a one-line diff nobody would notice. A failing CI check is noticeable. If
// either is genuinely worth restoring, deleting this file is a visible, arguable act in a diff.
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import watchlist from "./watchlist.json" with { type: "json" };

describe("Bjakcareer stays out of the watchlist", () => {
  it("has no entry, by slug or company name", () => {
    const hits = watchlist.filter((e) => /bjak/i.test(`${e?.slug || ""} ${e?.company || ""}`));
    expect(hits).toEqual([]);
  });
  it("the watchlist is still a real list (so an empty file cannot pass the check above)", () => {
    expect(Array.isArray(watchlist)).toBe(true);
    expect(watchlist.length).toBeGreaterThan(3000);
  });
});

describe("We Work Remotely stays unwired", () => {
  // Parses the REAL source, the way cron-chain.test.mjs parses the real chain: an assertion about
  // what the code actually wires beats an assertion about what a helper returns.
  const boards = readFileSync(new URL("./scan-boards.mjs", import.meta.url), "utf8");
  const defsLine = boards.split("\n").find((l) => /const defs\s*=/.test(l)) || "";

  it("is not in fetchBoardJobs's defs", () => {
    expect(defsLine).not.toMatch(/weworkremotely/i);
  });
  it("the defs line still wires the boards we DO keep (a renamed variable cannot fake a pass)", () => {
    for (const src of ["remoteok", "remotive", "himalayas"]) expect(defsLine).toMatch(src);
  });

  // The failure mode this pins: a source dropped from the fetcher but left in health-check's
  // `expected` list reports "boards down" on every single run, forever. An alarm that is always on is
  // an alarm nobody reads, which is how a REAL board outage gets missed.
  it("is not in health-check's expected board list either", () => {
    const hc = readFileSync(new URL("./health-check.mjs", import.meta.url), "utf8");
    const expectedLine = hc.split("\n").find((l) => /const expected\s*=.*remoteok/.test(l)) || "";
    expect(expectedLine).not.toMatch(/weworkremotely/i);
    expect(expectedLine).toMatch(/remoteok/);
  });
});
